# ---------------------------------------------------------------- arranged for tools/music.py
# The shop's score (owner, 2026-10-08): Tennent's data throughout; the run is bars 1-35 (phase 15: Bach's pulse intro, 1-3, then the theme). tools/music.py takes bars as
# (bar, bass, chords, melody, inner). The left hand's identity is its repeated eighths, so every eighth gets one
# chord: every left note sounding then (a held note joins each eighth it covers). The bass is the lowest of
# those, an octave down (the bass recorder sits an octave above Bach's bass: D3, G3, C3, F3... in bars 4-10),
# held while it repeats. A melody bar that only repeats one or two notes in eighths (bars 36-38) is the pulse
# moving up a voice, so it joins the chords; no bar has notes under the melody.
def _arranged(bar, melody, left):
	if len(melody) >= 5 and all(d == 0.5 for _, _, d in melody) and len({n for _, n, _ in melody}) <= 2:
		left, melody = left + melody, []
	chords, lows = [], []
	for k in range(6):
		t = 0.5 * k
		notes = sorted({n for s, n, d in left if s <= t < s + d})
		if notes:
			chords.append((t, notes, 0.5))
			lows.append((t, notes[0] - 12))
	bass = []
	for t, n in lows:
		if bass and bass[-1][1] == n and abs(bass[-1][0] + bass[-1][2] - t) < 1e-9:
			bass[-1] = (bass[-1][0], n, bass[-1][2] + 0.5)
		else:
			bass.append((t, n, 0.5))
	return (bar, bass, chords, melody, [])


